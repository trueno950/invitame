import {
  IsDefined,
  IsISO8601,
  IsOptional,
  IsUUID,
  Validate,
  ValidatorConstraint,
  type ValidatorConstraintInterface,
} from "class-validator";

/**
 * The field must be present in the payload, but `null` is a meaningful value (it clears the stored phone), so
 * `class-validator`'s `IsDefined` — which refuses both `undefined` and `null` — cannot state this rule.
 */
@ValidatorConstraint({ name: "isProvided" })
class IsProvidedConstraint implements ValidatorConstraintInterface {
  validate(value: unknown): boolean {
    return value !== undefined;
  }

  defaultMessage(): string {
    return "$property must be provided; null clears it";
  }
}

/** `@IsProvided()`: the property is present, and any value it carries — including `null` — is accepted. */
export function IsProvided(): PropertyDecorator {
  return Validate(IsProvidedConstraint);
}

/**
 * `POST /invitations` body (M4 T4; S1, S6, S9). The pinned template version and the package the entitlements
 * are checked against; nothing else. The owner is never a field: it comes from the session only (S9), and the
 * global pipe rejects any other field (`forbidNonWhitelisted`), so a request cannot even offer one. The slug is
 * generated by the API and the content starts empty, so neither is accepted here.
 */
export class CreateInvitationDto {
  @IsUUID("all")
  templateVersionId!: string;

  @IsUUID("all")
  packageId!: string;
}

/**
 * `PUT /invitations/:id/content` body (S7). Only presence is checked here: the pinned version's schema owns what
 * the content may contain, and its issues reach the client through `InvalidInvitationContentError`. `PUT` and
 * not `PATCH` because the whole content is replaced, and the web client sends it from a server action.
 */
export class UpdateInvitationContentDto {
  @IsDefined()
  content!: unknown;

  /** The `updatedAt` the client read, so the write applies only while the row still has that instant (S2). */
  @IsOptional()
  @IsISO8601()
  expectedUpdatedAt?: string;
}

/**
 * `PUT /invitations/:id/features` body (F1, F6; S4, S7). The zone, the phone, and the playlist link are required and every
 * value is validated by the domain, which owns the time zone allow-list, the phone rules, the playlist host allow-list,
 * the itinerary payload (F1; L3.1) with the gift registry (F2; L4.1), the lodging (F4; L7.1), the livestream (F9; L12.1),
 * the reminder switches (F6; L9.1), and the opening animation switch (F10; L14.3); only their presence is checked here, so
 * a value the domain refuses reaches the
 * client as 400 `INVALID_INVITATION_FEATURES` with its issues. `whatsappPhone`, `playlistUrl`, `itinerary`,
 * `giftRegistry`, `lodging`, `livestream`, and `reminders` accept null or an empty value to clear the stored one. Every field is required because this is a `PUT`: the whole feature data is replaced, so a body that
 * omits one is refused by the global pipe (400) instead of clearing data the client never mentioned. `PUT` not
 * `PATCH`, and the web client sends it from a server action, like a content save.
 */
export class UpdateInvitationFeaturesDto {
  @IsProvided()
  timeZone!: unknown;

  @IsProvided()
  whatsappPhone!: unknown;

  @IsProvided()
  playlistUrl!: unknown;

  /**
   * Optional, unlike the other three: a body that omits it keeps the stored itinerary (F1; review R3-001), so a client
   * built before the itinerary existed can still save its time zone, phone, and playlist without clearing a plan it
   * never knew about. `null` or an empty list still clears it.
   */
  @IsOptional()
  itinerary?: unknown;

  /**
   * Optional like the itinerary, and for the same reason (F2; L4.3): a body that omits it keeps the stored gift
   * registry, so a client built before F2 can still save the time zone, phone, and playlist without clearing a
   * registry it never knew about. `null` or a payload that would show nothing clears it.
   */
  @IsOptional()
  giftRegistry?: unknown;

  /**
   * Optional like the itinerary and the gift registry, and for the same reason (F4; L7.3): a body that omits it keeps
   * the stored lodging, so a client built before F4 can still save the time zone, phone, and playlist without clearing
   * cards it never knew about. `null` or a payload with no hotel and no transport line clears it.
   */
  @IsOptional()
  lodging?: unknown;

  /**
   * Optional like the fields above, and for the same reason (F9; L12.1): a body that omits it keeps the stored
   * livestream, so a client built before F9 can still save the rest without clearing a link it never knew about. `null`
   * or a payload without a link clears it.
   */
  @IsOptional()
  livestream?: unknown;

  /**
   * Optional like the fields above, and for the same reason (F6; L9.1): a body that omits it keeps the stored reminder
   * switches, so a client built before F6 can still save the rest without switching a reminder off that it never knew
   * about. `null` or a pair with nothing switched on clears them.
   */
  @IsOptional()
  reminders?: unknown;

  /**
   * Optional like the fields above: a body that omits it keeps the stored opening animation switch (F10; L14.3). It is
   * the owner's boolean, so a client built before F10 can still save the rest without turning an animation off that it
   * never knew about, and `false` is what switches it off.
   */
  @IsOptional()
  openingAnimation?: unknown;

  /**
   * Optional like the fields above (F14; L19.1): a body that omits it keeps the stored language, so a client built before
   * F14 can still save the rest without clearing a language it never knew about. `es`, `es-en`, and `en` are the only
   * accepted values, and the domain names the issue of any other one.
   */
  @IsOptional()
  language?: unknown;
}

/**
 * `PUT /invitations/:id/slug` body (F11; S2.11, L15.3). The address the owner typed. Only presence is checked here:
 * the domain owns the 3-to-40-character rule, the no-double-hyphen rule, and the reserved words, so a value it refuses
 * reaches the client as 400 `INVALID_INVITATION_SLUG` (or `INVITATION_SLUG_RESERVED`) with its issue. `PUT` and not
 * `PATCH` because the whole address is replaced, and the web client sends it from a server action.
 */
export class UpdateInvitationSlugDto {
  @IsDefined()
  slug!: unknown;
}

/**
 * `PUT /invitations/:id/places/:field` body (S2, S3). The label the geocoder answered and the two coordinates that
 * make it precise. Only presence is checked here: the domain owns the label bounds and the coordinate ranges, so a
 * value it refuses reaches the client as 400 `INVALID_INVITATION_PLACE` with its issues. A missing or null field is a
 * malformed request (400 from the global pipe), because a `PUT` states the whole point.
 */
export class UpdateInvitationPlaceDto {
  @IsDefined()
  label!: unknown;

  @IsDefined()
  lat!: unknown;

  @IsDefined()
  lng!: unknown;
}
