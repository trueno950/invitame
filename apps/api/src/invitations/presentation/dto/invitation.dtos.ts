import {
  IsDefined,
  IsISO8601,
  IsOptional,
  IsUUID,
  Validate,
  ValidatorConstraint,
  type ValidatorConstraintInterface,
} from "class-validator";

/**
 * The field must be present in the payload, but `null` is a meaningful value (it clears the stored phone), so
 * `class-validator`'s `IsDefined` — which refuses both `undefined` and `null` — cannot state this rule.
 */
@ValidatorConstraint({ name: "isProvided" })
class IsProvidedConstraint implements ValidatorConstraintInterface {
  validate(value: unknown): boolean {
    return value !== undefined;
  }

  defaultMessage(): string {
    return "$property must be provided; null clears it";
  }
}

/** `@IsProvided()`: the property is present, and any value it carries — including `null` — is accepted. */
export function IsProvided(): PropertyDecorator {
  return Validate(IsProvidedConstraint);
}

/**
 * `POST /invitations` body (M4 T4; S1, S6, S9). The pinned template version and the package the entitlements
 * are checked against; nothing else. The owner is never a field: it comes from the session only (S9), and the
 * global pipe rejects any other field (`forbidNonWhitelisted`), so a request cannot even offer one. The slug is
 * generated by the API and the content starts empty, so neither is accepted here.
 */
export class CreateInvitationDto {
  @IsUUID("all")
  templateVersionId!: string;

  @IsUUID("all")
  packageId!: string;
}

/**
 * `PUT /invitations/:id/content` body (S7). Only presence is checked here: the pinned version's schema owns what
 * the content may contain, and its issues reach the client through `InvalidInvitationContentError`. `PUT` and
 * not `PATCH` because the whole content is replaced, and the web client sends it from a server action.
 */
export class UpdateInvitationContentDto {
  @IsDefined()
  content!: unknown;

  /** The `updatedAt` the client read, so the write applies only while the row still has that instant (S2). */
  @IsOptional()
  @IsISO8601()
  expectedUpdatedAt?: string;
}

/**
 * `PUT /invitations/:id/features` body (F1, F6; S4, S7). Every field is required and every value is validated by
 * the domain, which owns the time zone allow-list, the phone rules, the playlist host allow-list, and the itinerary
 * payload (F1; L3.1) with the gift registry (F2; L4.1); only their presence is checked here, so a value the domain
 * refuses reaches the client as 400 `INVALID_INVITATION_FEATURES` with its issues. `whatsappPhone`, `playlistUrl`,
 * `itinerary`, and `giftRegistry` accept null or an empty value to clear the stored one. Every field is required because this is a `PUT`: the whole feature data is
 * replaced, so a body that omits one is refused by the global pipe (400) instead of clearing data the client never
 * mentioned. `PUT` not `PATCH`, and the web client sends it from a server action, like a content save.
 */
export class UpdateInvitationFeaturesDto {
  @IsProvided()
  timeZone!: unknown;

  @IsProvided()
  whatsappPhone!: unknown;

  @IsProvided()
  playlistUrl!: unknown;

  /**
   * Optional, unlike the other three: a body that omits it keeps the stored itinerary (F1; review R3-001), so a client
   * built before the itinerary existed can still save its time zone, phone, and playlist without clearing a plan it
   * never knew about. `null` or an empty list still clears it.
   */
  @IsOptional()
  itinerary?: unknown;

  /**
   * Optional like the itinerary, and for the same reason (F2; L4.3): a body that omits it keeps the stored gift
   * registry, so a client built before F2 can still save the time zone, phone, and playlist without clearing a
   * registry it never knew about. `null` or a payload that would show nothing clears it.
   */
  @IsOptional()
  giftRegistry?: unknown;
}

/**
 * `PUT /invitations/:id/places/:field` body (S2, S3). The label the geocoder answered and the two coordinates that
 * make it precise. Only presence is checked here: the domain owns the label bounds and the coordinate ranges, so a
 * value it refuses reaches the client as 400 `INVALID_INVITATION_PLACE` with its issues. A missing or null field is a
 * malformed request (400 from the global pipe), because a `PUT` states the whole point.
 */
export class UpdateInvitationPlaceDto {
  @IsDefined()
  label!: unknown;

  @IsDefined()
  lat!: unknown;

  @IsDefined()
  lng!: unknown;
}
