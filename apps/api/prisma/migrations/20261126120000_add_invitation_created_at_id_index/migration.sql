-- The unfiltered page of the administrator's status view (M9 T2; S1, T5) reads every invitation newest first:
-- `ORDER BY "createdAt" DESC, "id" DESC LIMIT n` with no status filter and no slug prefix. The status index
-- `Invitation_status_createdAt_idx` leads with `status`, so PostgreSQL cannot use it for that global order; this index
-- can, and its second key `id` is also the key-set cursor's tie-break, so a later page continues with a range scan of
-- the same index instead of a sort over the table.
--
-- Additive only: no row is rewritten, no column is added, and no default is needed. Prisma generated the index below
-- from `@@index([createdAt, id])`; `schema.prisma` and `docs/database/model.md` state which read it serves.
--
-- Build: `CREATE INDEX CONCURRENTLY` is what this statement uses, so it never takes the SHARE lock a plain build takes
-- and concurrent writes to `Invitation` keep working while the index is built. It was tested against PostgreSQL 17.11
-- through `pnpm --filter @invitame/api prisma:migrate:deploy` on a disposable database, which applies this migration
-- outside a transaction block and left a valid index (`indisvalid = true`) with the migration recorded as applied. If a
-- future Prisma version wraps migration files in a transaction, PostgreSQL answers "CREATE INDEX CONCURRENTLY cannot
-- run inside a transaction block", so re-test this file whenever Prisma is upgraded.
--
-- Rollback / recovery: the change is additive, so recovery is either applying the previous migration set or dropping
-- the index by hand. Dropping it costs the unfiltered page its index and nothing else; no data is touched. Run it as
-- its own migration, never by editing this file after it was applied:
--   DROP INDEX "Invitation_createdAt_id_idx";
-- If a concurrent build is ever interrupted it leaves an INVALID index behind: `IF NOT EXISTS` would then skip the
-- rebuild, so drop the leftover by hand (`DROP INDEX "Invitation_createdAt_id_idx"`) before re-running.

-- CreateIndex
CREATE INDEX CONCURRENTLY IF NOT EXISTS "Invitation_createdAt_id_idx" ON "Invitation"("createdAt", "id");
